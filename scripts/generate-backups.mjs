import fs from 'node:fs';
import path from 'node:path';

// Read .env.local
const envPath = path.resolve(process.cwd(), '.env.local');
const envContent = fs.readFileSync(envPath, 'utf8');
const env = {};
for (const line of envContent.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const eq = trimmed.indexOf('=');
  if (eq > 0) env[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
}

console.log('Fetching live snapshot from Supabase...');
const url = new URL('/rest/v1/rpc/nexacart_snapshot', env.SUPABASE_URL);
const res = await fetch(url, {
  method: 'POST',
  headers: {
    'Content-Type': 'application/json',
    apikey: env.SUPABASE_SERVICE_ROLE_KEY,
    Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`
  },
  body: JSON.stringify({})
});

if (!res.ok) {
  console.error('Failed to fetch snapshot:', await res.text());
  process.exit(1);
}

const data = await res.json();
const tables = data.tables;

const backupDir = path.resolve(process.cwd(), 'database/backups');
fs.mkdirSync(backupDir, { recursive: true });

function escapeSql(val) {
  if (val == null) return 'NULL';
  if (typeof val === 'number') return String(val);
  return `'${String(val).replace(/'/g, "''")}'`;
}

// 1. dim_seller
const sellerRows = tables.dim_seller.rows;
const sellerValues = sellerRows.map(r => `(${r.seller_id}, ${escapeSql(r.shop_name)}, ${escapeSql(r.seller_city)})`).join(',\n');
const sellerSql = `-- NexaCart Emergency Recovery: dim_seller
-- Run in Supabase SQL editor to restore dim_seller and 30 stores
CREATE TABLE IF NOT EXISTS public.dim_seller (
  seller_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_name text NOT NULL,
  seller_city text NOT NULL
);

ALTER TABLE public.dim_seller ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.dim_seller TO service_role;
GRANT SELECT ON public.dim_seller TO anon, authenticated;

INSERT INTO public.dim_seller (seller_id, shop_name, seller_city) VALUES
${sellerValues}
ON CONFLICT (seller_id) DO UPDATE SET
  shop_name = EXCLUDED.shop_name,
  seller_city = EXCLUDED.seller_city;

SELECT setval(pg_get_serial_sequence('public.dim_seller', 'seller_id'), coalesce((SELECT max(seller_id) FROM public.dim_seller), 1));

DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name='fact_order_items')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_seller') THEN
    ALTER TABLE public.fact_order_items ADD CONSTRAINT fk_seller FOREIGN KEY (seller_id) REFERENCES public.dim_seller(seller_id);
  END IF;
END $$;

NOTIFY pgrst, 'reload schema';
`;
fs.writeFileSync(path.join(backupDir, 'restore_dim_seller.sql'), sellerSql);

